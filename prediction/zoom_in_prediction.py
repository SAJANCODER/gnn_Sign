def load_inference_model(model_path, classes_file='classes.txt'):
    """
    Loads the trained Keras model and class names.
    """
    # Ensure custom objects are available for model loading
    custom_objects = {
        'CustomGCNConv': CustomGCNConv,
        'GlobalSumPool': GlobalSumPool
    }

    try:
        model = tf.keras.models.load_model(model_path,
                                           custom_objects=custom_objects)
        print(f"✅ Model loaded successfully from {model_path}")
    except Exception as e:
        print(f"🚫 Error loading model from {model_path}: {e}")
        print(
            "Please ensure 'full_model.h5' exists and the custom layers (CustomGCNConv, GlobalSumPool) are correctly defined/imported.")
        return None, None

    # Load class labels from the file generated by train_model.py (or data_preprocessing.py)
    classes = []
    if os.path.exists(classes_file):
        try:
            with open(classes_file, 'r') as f:
                classes = [line.strip() for line in f if line.strip()]
            print(f"✅ Classes loaded: {classes}")
        except Exception as e:
            print(f"🚫 Error loading classes from {classes_file}: {e}")
            return None, None
    else:
        print(
            f"🚫 Error: {classes_file} not found. Please ensure train_model.py was run successfully to generate this file in the expected location.")
        return None, None

    if not classes:
        print(f"🚫 Warning: No classes found in {classes_file}. Prediction will not display class names.")

    return model, classes


def preprocess_frame(frame, mp_hands):
    """
    Processes a video frame to extract MediaPipe hand landmarks.
    Returns landmarks as (1, 21, 3) numpy array and MediaPipe results object.
    """
    image_rgb = cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)
    # MediaPipe expects a writable image, so make a copy
    image_rgb.flags.writeable = False
    results = mp_hands.process(image_rgb)
    image_rgb.flags.writeable = True

    landmarks = None
    if results.multi_hand_landmarks:
        # Assuming we focus on the first detected hand for landmark extraction
        # If your model handles multiple hands, you might need to iterate
        hand_landmarks = results.multi_hand_landmarks[0]
        landmarks = np.array([[lm.x, lm.y, lm.z] for lm in hand_landmarks.landmark]).flatten()

        # Reshape for model input: (batch_size=1, num_landmarks=21, num_features=3)
        landmarks = landmarks.reshape(1, 21, 3).astype(np.float32)

    return landmarks, results


def create_adjacency_matrix(num_landmarks=21):
    """
    Creates the fixed adjacency matrix for hand landmarks.
    This must be identical to the one used during training.
    """
    connections = [
        (0, 1), (1, 2), (2, 3), (3, 4),  # Thumb
        (0, 5), (5, 6), (6, 7), (7, 8),  # Index finger
        (0, 9), (9, 10), (10, 11), (11, 12),  # Middle finger
        (0, 13), (13, 14), (14, 15), (15, 16),  # Ring finger
        (0, 17), (17, 18), (18, 19), (19, 20),  # Pinky finger
        (5, 9), (9, 13), (13, 17)  # Connecting bases of fingers (metacarpals)
    ]

    adj_matrix = np.eye(num_landmarks, dtype=np.float32)  # Add self-loops
    for u, v in connections:
        adj_matrix[u, v] = 1.0
        adj_matrix[v, u] = 1.0
    return adj_matrix[np.newaxis, :, :]  # Add batch dimension (1, 21, 21) for model input


def visualize_landmarks(image, results, mp_drawing, mp_hand_connections):
    """
    Draws hand landmarks and a bounding box around the detected hand(s) on the image.
    Returns the image with drawings and the bounding box coordinates for the first hand.
    """
    bbox_coords = None
    h, w, c = image.shape

    if results.multi_hand_landmarks:
        # We'll focus on the first detected hand for the cropped image
        hand_landmarks = results.multi_hand_landmarks[0]

        # Draw landmarks for all detected hands
        for hl in results.multi_hand_landmarks:
            mp_drawing.draw_landmarks(
                image,
                hl,
                mp_hand_connections.HAND_CONNECTIONS,
                mp_drawing.DrawingSpec(color=(0, 0, 255), thickness=2, circle_radius=2),  # Red dots
                mp_drawing.DrawingSpec(color=(0, 255, 0), thickness=2, circle_radius=2)  # Green lines
            )

        # Calculate bounding box for the first detected hand
        x_coords = [landmark.x for landmark in hand_landmarks.landmark]
        y_coords = [landmark.y for landmark in hand_landmarks.landmark]

        min_x, max_x = min(x_coords), max(x_coords)
        min_y, max_y = min(y_coords), max(y_coords)

        # Convert normalized coordinates to pixel coordinates
        x1 = int(min_x * w)
        y1 = int(min_y * h)
        x2 = int(max_x * w)
        y2 = int(max_y * h)

        # Add some padding to the bounding box
        padding_pixels = 40  # Increased padding for better visibility and ensuring hand is fully captured
        x1 = max(0, x1 - padding_pixels)
        y1 = max(0, y1 - padding_pixels)
        x2 = min(w, x2 + padding_pixels)
        y2 = min(h, y2 + padding_pixels)

        cv2.rectangle(image, (x1, y1), (x2, y2), (255, 0, 0), 2)  # Blue bounding box
        bbox_coords = (y1, y2, x1, x2)  # Format as (y_min, y_max, x_min, x_max) for slicing

    return image, bbox_coords


def crop_and_resize_hand(frame, bbox_coords, target_size=(224, 224)):
    """
    Crops the hand region from the frame using bounding box coordinates
    and resizes it to the target dimensions.
    Returns the cropped and resized image.
    """
    if bbox_coords is None:
        return np.zeros((target_size[0], target_size[1], 3), dtype=np.uint8)  # Return black image if no hand

    y1, y2, x1, x2 = bbox_coords

    # Ensure coordinates are within frame boundaries
    h, w, _ = frame.shape
    y1 = max(0, y1)
    y2 = min(h, y2)
    x1 = max(0, x1)
    x2 = min(w, x2)

    cropped_hand = frame[y1:y2, x1:x2]

    if cropped_hand.shape[0] == 0 or cropped_hand.shape[1] == 0:
        return np.zeros((target_size[0], target_size[1], 3), dtype=np.uint8)  # Return black image if crop is empty

    # Resize the cropped hand to the target size
    resized_hand = cv2.resize(cropped_hand, target_size, interpolation=cv2.INTER_AREA)

    return resized_hand


def main():
    model_path = 'full_model.h5'  # Path to your trained model
    classes_file = 'classes_full_1.txt'  # Path to your classes file

    model, classes = load_inference_model(model_path, classes_file)
    if model is None:  # If model failed to load, exit
        return

    mp_hands = mp.solutions.hands
    mp_drawing = mp.solutions.drawing_utils

    cap = cv2.VideoCapture(0)  # 0 for default webcam
    if not cap.isOpened():
        print("Error: Could not open webcam. Make sure it's connected and not in use.")
        return

    # Create the fixed adjacency matrix once
    fixed_A = create_adjacency_matrix()

    print(
        f"\nStarting real-time prediction. Model input image size: {TARGET_IMG_SIZE[0]}x{TARGET_IMG_SIZE[1]} pixels. Press 'q' to quit.")

    # Initialize MediaPipe Hands model for real-time processing
    with mp_hands.Hands(min_detection_confidence=0.7, min_tracking_confidence=0.5,
                        max_num_hands=1) as hands:  # Changed to max_num_hands=1 if your model is single-hand focused
        prev_frame_time = 0
        new_frame_time = 0
        while cap.isOpened():
            ret, frame = cap.read()
            if not ret:
                print("Failed to grab frame.")
                break

            frame = cv2.flip(frame, 1)  # Flip horizontally for mirrored view

            landmarks, results = preprocess_frame(frame, hands)

            display_text = "No Hand Detected"
            zoomed_hand_display = np.zeros((TARGET_IMG_SIZE[0], TARGET_IMG_SIZE[1], 3),
                                           dtype=np.uint8)  # Initialize as black

            # Draw landmarks and get bounding box coordinates
            frame, bbox_coords = visualize_landmarks(frame, results, mp_drawing, mp_hands)

            if landmarks is not None and bbox_coords is not None:
                # Crop and resize the detected hand
                zoomed_hand_image = crop_and_resize_hand(frame, bbox_coords, TARGET_IMG_SIZE)

                # Convert to RGB and add batch dimension for the model if needed (if your model expects image input)
                # NOTE: Your original model takes landmarks (1, 21, 3) and adjacency matrix (1, 21, 21).
                # If your model needs a 224x224 image input, you will need to adapt the model.predict call.
                # For now, we will just display the zoomed hand.
                # If you train a new model with image input, you would do something like:
                # model_input_image = cv2.cvtColor(zoomed_hand_image, cv2.COLOR_BGR2RGB)
                # model_input_image = np.expand_dims(model_input_image, axis=0) / 255.0 # Normalize if your model expects [0,1]
                # predictions = model.predict(model_input_image, verbose=0)

                # The original model uses landmarks, so the prediction logic remains the same for now:
                predictions = model.predict([landmarks, fixed_A], verbose=0)
                predicted_class_idx = np.argmax(predictions[0])
                confidence = predictions[0][predicted_class_idx]

                CONFIDENCE_THRESHOLD = 0.7  # Adjust as needed

                if classes and confidence > CONFIDENCE_THRESHOLD:
                    predicted_class_name = classes[predicted_class_idx]
                    display_text = f"{predicted_class_name} ({confidence * 100:.2f}%)"
                else:
                    display_text = "Uncertain / No Clear Sign"

                # Set zoomed_hand_display for showing
                zoomed_hand_display = zoomed_hand_image

            # Calculate and display FPS
            new_frame_time = time.time()
            fps = 1 / (new_frame_time - prev_frame_time)
            prev_frame_time = new_frame_time
            cv2.putText(frame, f"FPS: {int(fps)}", (frame.shape[1] - 120, 30), cv2.FONT_HERSHEY_SIMPLEX, 0.8,
                        (255, 0, 0), 2, cv2.LINE_AA)

            # Display prediction text on the main frame
            cv2.putText(frame, display_text, (10, 30), cv2.FONT_HERSHEY_SIMPLEX, 1, (0, 255, 0), 2, cv2.LINE_AA)

            cv2.imshow('ISL Recognition (Main)', frame)
            cv2.imshow('Detected Hand (Zoomed 224x224)', zoomed_hand_display)  # Show the zoomed hand

            if cv2.waitKey(1) & 0xFF == ord('q'):
                break

    cap.release()
    cv2.destroyAllWindows()
    print("Real-time prediction stopped.")


